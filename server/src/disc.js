export function scoreDisc(answers) {
  const scores = { D: 0, I: 0, S: 0, C: 0 };
  for (const q of DISC_QUESTIONS) {
    const pick = answers?.[q.id];
    if (pick && scores[pick] !== undefined) scores[pick]++;
  }
  // основен стил – най-висок резултат; при равенство по реда D, I, S, C
  const primary = ['D', 'I', 'S', 'C'].reduce((best, k) => (scores[k] > scores[best] ? k : best), 'D');
  return { scores, primary };
}
